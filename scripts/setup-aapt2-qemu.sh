#!/usr/bin/env bash
#
# setup-aapt2-qemu.sh — let an arm64 host run AGP's x86_64 aapt2.
#
# Why this exists: the Android Gradle plugin ships aapt2 as a **x86_64 Linux**
# binary. On an arm64 machine (a phone running proot, a Raspberry Pi, an
# arm64 container) it cannot execute, and the build dies with the famously
# unhelpful:
#
#     AAPT2 ... Daemon #0: Daemon startup failed. This should not happen
#     under normal circumstances.
#
# AGP 8.7 has no "use the system aapt2" switch for the daemon — but it does
# honour `android.aapt2FromMavenOverride`, which accepts any executable. So we
# point that at a two-line shim that runs the real binary under qemu-x86_64,
# with a throwaway amd64 glibc for it to link against.
#
# Idempotent: re-running is cheap and does nothing if the shim already works.
#
# Usage:
#   ./scripts/setup-aapt2-qemu.sh          # set up (or verify) the shim
#   ./scripts/setup-aapt2-qemu.sh --check  # exit 0 if already working

set -euo pipefail

AAPT2_SYSROOT="${AAPT2_SYSROOT:-/tmp/amd64-sysroot}"
AAPT2_SHIM_DIR="${AAPT2_SHIM_DIR:-/root/tools/aapt2-bin}"
SHIM="$AAPT2_SHIM_DIR/aapt2"

ok() { printf '  %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# Already good? Then there is nothing to do.
if [[ -x "$SHIM" ]] && "$SHIM" version >/dev/null 2>&1; then
    if [[ "${1:-}" == "--check" ]]; then
        exit 0
    fi
    ok "aapt2 shim already works: $SHIM"
    exit 0
fi
[[ "${1:-}" == "--check" ]] && exit 1

command -v qemu-x86_64 >/dev/null 2>&1 ||
    die "qemu-x86_64 not found — install it (apt-get install -y qemu-user)"

# ── 1. Find the real aapt2 AGP downloaded ────────────────────────────────────
REAL="$(find "${GRADLE_USER_HOME:-$HOME/.gradle}/caches" \
    -path "*transformed/aapt2-*-linux/aapt2" -type f 2>/dev/null | head -1)"
[[ -n "$REAL" ]] ||
    die "no aapt2 in the Gradle cache yet — run any Gradle task once so AGP downloads it"

# ── 2. Fetch an amd64 glibc for the x86_64 binary to link against ────────────
# The host is arm64, so /lib/x86_64-linux-gnu does not exist and there is
# nothing for the loader to use. Ubuntu's amd64 packages are in the normal
# archive (ports.ubuntu.com only carries arm64), and apt on a port-enabled
# box will not resolve them, so fetch the three .deb files directly.
if [[ ! -e "$AAPT2_SYSROOT/usr/lib/x86_64-linux-gnu/libc.so.6" ]]; then
    ok "fetching amd64 libc into $AAPT2_SYSROOT"
    python3 - "$AAPT2_SYSROOT" <<'PY'
import gzip, io, os, re, sys, urllib.request

root = sys.argv[1]
base = "http://archive.ubuntu.com/ubuntu"
want = {"libc6", "libgcc-s1", "libcrypt1"}
hdr = {"User-Agent": "curl/8"}

def fetch(url):
    return urllib.request.urlopen(
        urllib.request.Request(url, headers=hdr), timeout=60).read()

found = {}
for suite in ("noble-updates/main", "noble/main"):
    text = gzip.GzipFile(fileobj=io.BytesIO(
        fetch(f"{base}/dists/{suite}/binary-amd64/Packages.gz"))).read().decode()
    for block in text.split("\n\n"):
        f = dict(re.findall(r"^(\S+):\s*(.*)$", block, re.M))
        if f.get("Package") in want and "amd64" in f.get("Architecture", ""):
            cur = found.get(f["Package"])
            if cur is None or f["Version"] > cur[0]:
                found[f["Package"]] = (f["Version"], f["Filename"])

missing = want - set(found)
if missing:
    sys.exit(f"missing from index: {sorted(missing)}")

os.makedirs(root, exist_ok=True)
for pkg, (_, path) in found.items():
    deb = os.path.join(root, os.path.basename(path))
    with open(deb, "wb") as fh:
        fh.write(fetch(f"{base}/{path}"))
    os.system(f"dpkg -x {deb!r} {root!r} && rm -f {deb!r}")
PY
    # usrmerge layout: make /lib and /lib64 resolve the way an amd64 root expects.
    ln -sfn usr/lib "$AAPT2_SYSROOT/lib"
    ln -sfn usr/lib64 "$AAPT2_SYSROOT/lib64"
fi
[[ -e "$AAPT2_SYSROOT/usr/lib/x86_64-linux-gnu/libc.so.6" ]] ||
    die "amd64 libc still missing from $AAPT2_SYSROOT"

# ── 3. Install the shim ─────────────────────────────────────────────────────
mkdir -p "$AAPT2_SHIM_DIR"
printf '#!/bin/sh\n# Generated by scripts/setup-aapt2-qemu.sh — runs AGP x86_64 aapt2 on arm64.\nexec qemu-x86_64 -L %s %s "$@"\n' \
    "$AAPT2_SYSROOT" "$REAL" > "$SHIM"
chmod +x "$SHIM"

"$SHIM" version >/dev/null 2>&1 ||
    die "shim still cannot run aapt2 — check $AAPT2_SYSROOT and $REAL"

ok "aapt2 shim ready: $SHIM"
ok "pass -Pandroid.aapt2FromMavenOverride=$SHIM to Gradle (build-apk.sh does this)"
